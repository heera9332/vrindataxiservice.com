            function setTripType(el, type) {
                if (typeof type === 'undefined') {
                    type = el;
                    el = null;
                }

                const tripInput = document.getElementById("tripType");
                if (tripInput) {
                    tripInput.value = type;
                }

                document.querySelectorAll('.trip-btn').forEach(btn => {
                    btn.classList.remove('active');
                    if (!el && btn.getAttribute('onclick') && btn.getAttribute('onclick').includes("'" + type + "'")) {
                        btn.classList.add('active');
                    }
                });

                if (el && el.classList) {
                    el.classList.add('active');
                }

                const wrapper = document.getElementById("returnDateWrapper");
                const returnInput = document.getElementById("returnDate");

                if (wrapper && returnInput) {
                    if (type === "round_trip") {
                        wrapper.style.display = "block";
                        returnInput.setAttribute("required", "required");
                    } else {
                        wrapper.style.display = "none";
                        returnInput.removeAttribute("required");
                        returnInput.value = "";
                    }
                }
            }


        function disablePastDates() {

            const now = new Date();
            now.setMinutes(now.getMinutes() - now.getTimezoneOffset());

            const minDateTime = now.toISOString().slice(0, 16);

            document.getElementById("pickupDate").min = minDateTime;
            document.getElementById("returnDate").min = minDateTime;
        }



        function calculateDistanceBeforeSubmit(event) {
            event.preventDefault();

            const form = event.target;
            const pickup = document.getElementById("pickup").value.trim();
            const drop = document.getElementById("drop").value.trim();
            const pickupDate = document.getElementById("pickupDate").value;
            const returnDate = document.getElementById("returnDate") ? document.getElementById("returnDate").value : '';
            let trip = document.getElementById("tripType").value;

            if(!trip || trip === 'undefined') {
                trip = 'local';
                document.getElementById('tripType').value = 'local';
            }

            if (!pickup || !drop || !pickupDate) {
                alert("Please fill all required fields (Pickup, Drop, and Date).");
                return false;
            }

            if (trip === "round_trip" && !returnDate) {
                alert("Please select return date.");
                return false;
            }

            function submitWithDistance(distKm) {
                document.getElementById("distanceKm").value = distKm;
                form.submit();
            }

            if (typeof google !== "undefined" && google.maps && google.maps.DistanceMatrixService) {
                const service = new google.maps.DistanceMatrixService();
                service.getDistanceMatrix({
                    origins: [pickup],
                    destinations: [drop],
                    travelMode: google.maps.TravelMode.DRIVING,
                    unitSystem: google.maps.UnitSystem.METRIC
                }, function(response, status) {
                    if (status === "OK" && response.rows && response.rows[0] && response.rows[0].elements[0] && response.rows[0].elements[0].status === "OK") {
                        const distanceKm = (response.rows[0].elements[0].distance.value / 1000).toFixed(2);
                        submitWithDistance(distanceKm);
                    } else {
                        submitWithDistance(25);
                    }
                });
            } else {
                submitWithDistance(25);
            }

            return false;
        }
        function initMap() {

            const pickupInput = document.getElementById("pickup");
